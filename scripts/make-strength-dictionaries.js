// Writes the password strength dictionaries in src/shared/strength/data/
// from the packages pinned in devDependencies:
//
//   node scripts/make-strength-dictionaries.js
//
// test/password-strength.test.js runs build() and checks that the committed
// files are what it produces. Sources and licenses are listed in NOTICE.md.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.join(__dirname, "..");
const OUTPUT = path.join(ROOT, "src", "shared", "strength", "data");
const SEPARATOR = "|";
// The most common words of each frequency list; rarer ones barely change an
// estimate. Lists not named here are kept whole.
const LIMITS = Object.freeze({ commonWords: 30000, wikipedia: 30000, lastnames: 20000 });
// Markup and web words in the Russian Wikipedia list, not Russian words.
const RUSSIAN_MARKUP = new Set([
  "doc", "ru", "org", "id", "https", "http", "url", "title", "wikipedia", "wiki", "curid",
  "km", "www", "html", "com", "isbn", "ref", "the",
]);

function packageInfo(name) {
  const manifest = require(`${name}/package.json`);
  return `${manifest.name}@${manifest.version}`;
}

function list(packageName, file) {
  return require(`${packageName}/src/${file}.json`);
}

// Lowercase, without repeats (the first, most common, rank wins), and cut to
// `limit` words. Entries with the separator are table markup
// ("colspan=3|total"), not words, and are left out.
function prepare(words, limit = Infinity, keep = () => true) {
  const seen = new Set();
  const result = [];
  for (const raw of words) {
    const word = raw.toLowerCase();
    if (seen.has(word) || word.includes(SEPARATOR) || !keep(word)) continue;
    seen.add(word);
    result.push(word);
    if (result.length >= limit) break;
  }
  return result;
}

// Attribution the data licenses ask for; it ships inside the data files.
const OPENSUBTITLES = [
  "commonWords: derived from OpenSubtitles 2024 (https://opus.nlpl.eu/),",
  "provided by Helsinki-NLP / OPUS under ODC-BY 1.0 (Open Data Commons",
  "Attribution License). Original data is attributed to subtitle",
  "contributors and rights holders. Processed: tokenized, frequencies",
  "aggregated, normalized and filtered, cut to the most common words.",
];
const EFF = [
  "diceware: the EFF large wordlist for passphrases",
  "(https://www.eff.org/dice), Electronic Frontier Foundation, CC BY 3.0 US.",
];

function moduleText(sources, notice, lists) {
  const lines = [
    "// Generated by scripts/make-strength-dictionaries.js; do not edit.",
    `// Source: ${sources} (MIT). See NOTICE.md.`,
    ...notice.map((line) => `// ${line}`),
    `// Words separated by "${SEPARATOR}", most common first.`,
  ];
  for (const [name, words] of Object.entries(lists)) {
    lines.push(`export const ${name} = ${JSON.stringify(words.join(SEPARATOR))};`);
  }
  return `${lines.join("\n")}\n`;
}

function languageModule(code) {
  const packageName = `@zxcvbn-ts/language-${code}`;
  const keep = code === "ru" ? (word) => /^[a-z]+$/.test(word) && !RUSSIAN_MARKUP.has(word) : () => true;
  const lists = {};
  for (const file of ["commonWords", "wikipedia", "firstnames", "lastnames"]) {
    lists[file] = prepare(list(packageName, file), LIMITS[file] ?? Infinity, file === "wikipedia" ? keep : () => true);
  }
  return moduleText(packageInfo(packageName), OPENSUBTITLES, lists);
}

// zxcvbn's keyboard graphs, as an ES module.
function graphsModule() {
  const graphs = require("zxcvbn/lib/adjacency_graphs");
  const lines = [
    "// Generated by scripts/make-strength-dictionaries.js; do not edit.",
    `// Source: ${packageInfo("zxcvbn")}. Copyright (c) 2012-2016 Dan Wheeler and`,
    "// Dropbox, Inc. MIT; see the notice in src/shared/strength/estimator.js.",
    "// Keyboard adjacency: for each key, its neighbors in each direction",
    "// (unshifted and shifted character), or null.",
  ];
  for (const name of ["qwerty", "dvorak", "keypad", "mac_keypad"]) {
    lines.push(`export const ${name.replace("_k", "K")} = ${JSON.stringify(graphs[name])};`);
  }
  return `${lines.join("\n")}\n`;
}

// { file name: contents } for src/shared/strength/data/.
function build() {
  return {
    "common.js": moduleText(
      packageInfo("@zxcvbn-ts/language-common"),
      EFF,
      {
        passwords: prepare(list("@zxcvbn-ts/language-common", "passwords")),
        diceware: prepare(list("@zxcvbn-ts/language-common", "diceware")),
      },
    ),
    "en.js": languageModule("en"),
    "de.js": languageModule("de"),
    "ru.js": languageModule("ru"),
    "graphs.js": graphsModule(),
  };
}

if (require.main === module) {
  fs.mkdirSync(OUTPUT, { recursive: true });
  for (const [name, contents] of Object.entries(build())) {
    fs.writeFileSync(path.join(OUTPUT, name), contents);
    console.log(`Wrote src/shared/strength/data/${name} (${Math.round(contents.length / 1024)} KB)`);
  }
}

module.exports = { OUTPUT, SEPARATOR, build };
